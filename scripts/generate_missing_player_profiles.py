def primary_role(profile: dict[str, Any]) -> str:
    role = profile["role"].lower()
    if "wicket" in role:
        return "wicket-keeper"
    if "all-rounder" in role:
        return "all-rounder"
    if "bowler" in role:
        return "bowler"
    if "batsman" in role or "batter" in role:
        return "batsman"
    return "player"


