def replace_style_background(html: str, background_image: str) -> str:
    pattern = r"(background-image:\s*url\(')([^']+)('\);)"
    return re.sub(pattern, rf"\1{background_image}\3", html, count=1)


def set_meta_content(soup: BeautifulSoup, *, attr_name: str, attr_value: str, content: str) -> None:
    tag = soup.find("meta", attrs={attr_name: attr_value})
    if tag:
        tag["content"] = content


def ensure_team_link_styles(soup: BeautifulSoup) -> None:
    style_tag = soup.find("style")
    if not style_tag:
        return

    css = style_tag.string or style_tag.get_text()
    if ".player-team-link" in css:
        return

    style_tag.string = css + """
        .player-team-link {
            display: inline-block;
            text-decoration: none;
            color: inherit;
        }

        .player-team-link:hover .team-name {
            color: #06b6d4;
        }
"""


def ensure_team_link_markup(soup: BeautifulSoup, team_slug: str | None) -> None:
    if not team_slug:
        return

    team_block = soup.select_one(".player-team")
    if team_block:
        href = f"/teams/{team_slug}"
        parent = team_block.parent
        if parent and getattr(parent, "name", None) == "a" and "player-team-link" in parent.get("class", []):
            parent["href"] = href
        else:
            team_link = soup.new_tag("a", href=href)
            team_link["class"] = ["player-team-link"]
            team_block.wrap(team_link)

    ensure_team_link_styles(soup)


def remove_view_all_players_button(soup: BeautifulSoup) -> None:
    for link in soup.find_all("a"):
        text = normalize_space(link.get_text(" ", strip=True))
        if text != "View All Players":
            continue

        parent = link.parent
        if parent and getattr(parent, "name", None) == "div":
            parent.decompose()
        else:
            link.decompose()


def ensure_real_social_links(soup: BeautifulSoup) -> None:
    for group in soup.select(".social-links, .footer-social"):
        anchors = [anchor for anchor in group.find_all("a", class_="social-link", recursive=False)]
        for index, anchor in enumerate(anchors):
            href = normalize_space(anchor.get("href"))
            if href and href != "javascript:void(0)":
                continue

            label = normalize_space(anchor.get("aria-label")).lower()
            key = next((name for name in SOCIAL_ORDER if name in label), None)
            if key is None and index < len(SOCIAL_ORDER):
                key = SOCIAL_ORDER[index]
                anchor["aria-label"] = key.title() if key != "youtube" else "YouTube"

            if key is None:
                continue

            anchor["href"] = SOCIAL_LINKS[key]
            anchor["target"] = "_blank"
            anchor["rel"] = "noopener noreferrer"


def render_generated_page(profile: dict[str, Any], profiles: dict[str, dict[str, Any]]) -> str:
    template_html = TEMPLATE_PATH.read_text(encoding="utf-8")
    soup = BeautifulSoup(template_html, "html.parser")

    title = title_for(profile["name"])
    description = description_for(profile)
    canonical = f"{SITE_URL}/players/{profile['slug']}"
    image_url = public_url(profile["image"])
    team_logo = TEAM_LOGOS.get(profile["team_slug"], DEFAULT_TEAM_LOGO)
    background_image = image_for_background(profile)

    if soup.title:
        soup.title.string = title

    set_meta_content(soup, attr_name="name", attr_value="description", content=description)
    set_meta_content(soup, attr_name="name", attr_value="keywords", content=f"{profile['name']}, {profile['name']} NPL 2026, {profile['team']}, Nepal Premier League")
    set_meta_content(soup, attr_name="property", attr_value="og:title", content=title)
    set_meta_content(soup, attr_name="property", attr_value="og:description", content=description)
    set_meta_content(soup, attr_name="property", attr_value="og:url", content=canonical)
    set_meta_content(soup, attr_name="property", attr_value="og:image", content=image_url)
    set_meta_content(soup, attr_name="name", attr_value="twitter:title", content=title)
    set_meta_content(soup, attr_name="name", attr_value="twitter:description", content=description)
    set_meta_content(soup, attr_name="name", attr_value="twitter:image", content=image_url)

    canonical_tag = soup.find("link", rel="canonical")
    if canonical_tag:
        canonical_tag["href"] = canonical

    structured = soup.find("script", attrs={"type": "application/ld+json"})
    if structured:
        structured.string = json.dumps(
            {
                "@context": "https://schema.org",
                "@type": "Person",
                "name": profile["name"],
                "memberOf": {"@type": "SportsTeam", "name": profile["team"]},
                "description": description,
                "url": canonical,
                "image": image_url,
            },
            ensure_ascii=False,
        )

    breadcrumb = soup.select_one(".breadcrumb-content")
    if breadcrumb:
        current_span = breadcrumb.find_all("span")[-1]
        current_span.string = profile["name"]

    player_title = soup.select_one(".player-title")
    if player_title:
        player_title.string = profile["name"]

    player_subtitle = soup.select_one(".player-subtitle")
    if player_subtitle:
        player_subtitle.string = SUBTITLE

    team_logo_tag = soup.select_one(".team-logo")
    if team_logo_tag:
        team_logo_tag["src"] = team_logo
        team_logo_tag["alt"] = profile["team"]

    team_name = soup.select_one(".team-name")
    if team_name:
        team_name.string = profile["team"]

    ensure_team_link_markup(soup, profile["team_slug"])
    remove_view_all_players_button(soup)
    ensure_real_social_links(soup)

    intro = soup.select_one(".intro-text")
    if intro:
        intro.clear()
        intro.append(BeautifulSoup(intro_for(profile), "html.parser"))

    overview = soup.select_one(".overview-content")
    if overview:
        overview.clear()
        overview.append(BeautifulSoup(overview_markup(profile), "html.parser"))

    related = soup.select_one(".related-players-content")
    if related:
        related.clear()
        related.append(BeautifulSoup(related_markup(profile, profiles), "html.parser"))

    body = soup.body
    if body and GENERATED_MARKER not in str(body):
        body.insert(0, BeautifulSoup(GENERATED_MARKER, "html.parser"))

    rendered = str(soup)
    rendered = replace_style_background(rendered, background_image)
    return rendered


def render_redirect_page(target_slug: str) -> str:
    target_url = f"/players/{target_slug}"
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Redirecting...</title>
    <meta name="robots" content="noindex, follow">
    <meta http-equiv="refresh" content="0; url={target_url}">
    <link rel="canonical" href="{SITE_URL}{target_url}">
    <script>window.location.replace("{target_url}" + window.location.search + window.location.hash);</script>
</head>
<body>
    {GENERATED_MARKER}
    <p>Redirecting to <a href="{target_url}">{target_url}</a>.</p>
</body>
</html>
"""


def normalize_existing_profile(path: Path) -> None:
    html = path.read_text(encoding="utf-8")
    if GENERATED_MARKER in html:
        return

    soup = BeautifulSoup(html, "html.parser")
    player_title = soup.select_one(".player-title")
    if not player_title:
        return

    name = normalize_space(player_title.get_text(" ", strip=True))
    title = title_for(name)

    if soup.title:
        soup.title.string = title

    set_meta_content(soup, attr_name="property", attr_value="og:title", content=title)
    set_meta_content(soup, attr_name="name", attr_value="twitter:title", content=title)

    subtitle = soup.select_one(".player-subtitle")
    if subtitle:
        subtitle.string = SUBTITLE

    team_name = soup.select_one(".team-name")
    team_slug = team_slug_from_name(team_name.get_text(" ", strip=True)) if team_name else None
    ensure_team_link_markup(soup, team_slug)
    remove_view_all_players_button(soup)
    ensure_real_social_links(soup)

    path.write_text(str(soup), encoding="utf-8")


def normalize_all_player_social_links() -> None:
    for path in PLAYERS_DIR.glob("*.html"):
        html = path.read_text(encoding="utf-8")
        soup = BeautifulSoup(html, "html.parser")
        before = str(soup)
        ensure_real_social_links(soup)
        after = str(soup)
        if after != before:
            path.write_text(after, encoding="utf-8")


def main() -> None:
    profiles = parse_team_profiles()

    for alias_slug, target_slug in ALIASES.items():
        (PLAYERS_DIR / f"{alias_slug}.html").write_text(render_redirect_page(target_slug), encoding="utf-8")

    for path in PLAYERS_DIR.glob("*.html"):
        normalize_existing_profile(path)

    for slug, profile in sorted(profiles.items()):
        if (PLAYERS_DIR / f"{slug}.html").exists():
            current = (PLAYERS_DIR / f"{slug}.html").read_text(encoding="utf-8")
            if GENERATED_MARKER not in current:
                continue
        profile["slug"] = slug
        (PLAYERS_DIR / f"{slug}.html").write_text(render_generated_page(profile, profiles), encoding="utf-8")

    normalize_all_player_social_links()


if __name__ == "__main__":
    main()
