def extract_team_name(path: Path, soup: BeautifulSoup) -> str:
    selectors = [".team-details h2", ".hero-content h1", "h1", "title"]
    for selector in selectors:
        node = soup.select_one(selector)
        if not node:
            continue
        text = normalize_space(node.get_text(" ", strip=True))
        for suffix in [" - Nepal Premier League", " Players", " Squad"]:
            if text.endswith(suffix):
                text = text[: -len(suffix)].strip()
        if text and text.lower() != "players":
            return text
    return path.stem.replace("-", " ").title()


def closest_player_card(node: Any) -> Any:
    current = node
    while current and getattr(current, "name", None) != "body":
        if "player-card" in current.get("class", []):
            return current
        current = current.parent
    return None


def parse_team_profiles() -> dict[str, dict[str, Any]]:
    image_index = build_image_index()
    profiles: dict[str, dict[str, Any]] = {}

    for team_file in sorted(TEAMS_DIR.glob("*.html")):
        soup = BeautifulSoup(team_file.read_text(encoding="utf-8"), "html.parser")
        team_name = extract_team_name(team_file, soup)
        team_slug = team_file.stem

        for link in soup.select('a[href^="/players/"]'):
            slug = link["href"].split("/players/", 1)[1].split("?", 1)[0].split("#", 1)[0].strip("/")
            if not slug:
                continue

            card = closest_player_card(link)
            if not card:
                continue

            name = normalize_space(card.select_one(".player-name").get_text(" ", strip=True) if card.select_one(".player-name") else "")
            role = normalize_space(card.select_one(".player-role").get_text(" ", strip=True) if card.select_one(".player-role") else "")
            if not role:
                badges = [
                    normalize_space(badge.get_text(" ", strip=True))
                    for badge in card.select(".role-badge")
                    if normalize_space(badge.get_text(" ", strip=True))
                ]
                role = " • ".join(badges) if badges else "Squad Player"

            image_node = card.select_one("img")
            image = asset_path(image_node["src"]) if image_node and image_node.get("src") else DEFAULT_IMAGE
            if image in {asset_path("/images/players/default-player.jpg"), asset_path("/images/Player.png")}:
                image = asset_path(image_index.get(slug, image_index.get(slugify(name), DEFAULT_IMAGE)))

            profiles[slug] = {
                "name": name or slug.replace("-", " ").title(),
                "slug": slug,
                "team": team_name,
                "team_slug": team_slug,
                "role": role,
                "image": image,
                "is_international": bool(card.select_one(".badge-intl")) or "international" in role.lower(),
                "is_captain": "captain" in role.lower(),
            }

    profiles.update(MANUAL_PROFILES)
    return profiles


def image_for_background(profile: dict[str, Any]) -> str:
    bg_candidates = [
        IMAGES_DIR / f"{profile['slug']}-bg.webp",
        IMAGES_DIR / f"{profile['slug']}-bg.jpg",
        IMAGES_DIR / f"{profile['slug']}-bg.png",
    ]
    for path in bg_candidates:
        if path.exists():
            return asset_path(f"/images/players/{path.name}")
    return profile["image"]


