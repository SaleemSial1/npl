def related_players(slug: str, profiles: dict[str, dict[str, Any]]) -> list[dict[str, Any]]:
    current = profiles[slug]
    teammates = [
        profile
        for other_slug, profile in profiles.items()
        if other_slug != slug and profile["team_slug"] == current["team_slug"]
    ]
    teammates.sort(key=lambda item: item["name"])
    return teammates[:4]


